local vals = {0.0, -0.0, 0.5, 1.5, 2.5, -2.5, 0.25, 0.125, 1.0, -1.0, 3.14159265358979,
  1e-5, 1e-4, 1e5, 1e6, 1e14, 1e15, 1e20, 1e-20, 1e100, 1e-100, 123456.789, -123456.789,
  0.1, 0.2, 1/3, 2/3, 9007199254740992.0, 1e308, 5e-324, 99999.5, 0.0001235,
  math.huge, -math.huge, 0/0, 1e13+0.5, 1234567890.12345, 655.35, 0.0000001}
local specs = {"%e","%E","%f","%g","%G","%.0f","%.1f","%.2f","%.9f","%.0e","%.1e","%.17e",
  "%.0g","%.1g","%.2g","%.5g","%.14g","%.17g","%12.4f","%-12.4f","%012.4f","%+.3f","% .3f",
  "%#g","%#.0f","%#.3g","%20g","%-20g","%020g","%+g","% g","%1.1g","%99.5f"}
for i = 1, #vals do
  local out = {}
  for j = 1, #specs do
    local ok, r = pcall(string.format, specs[j], vals[i])
    out[#out+1] = specs[j] .. "=[" .. (ok and r or "ERR") .. "]"
  end
  print(i, table.concat(out, "\t"))
end
